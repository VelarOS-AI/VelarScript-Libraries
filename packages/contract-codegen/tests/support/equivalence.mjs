// Runs the golden equivalence sweep: the same payload is offered to the zod
// schema and to the generated VelarScript type, and the two answers must agree
// except in the divergence classes the mapping table declares.

import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export const PACKAGE_ROOT = join(here, "..", "..");
export const FIXTURES = join(PACKAGE_ROOT, "tests", "fixtures");

/**
 * A fixture copy outside the repository still has to resolve the target's own
 * zod, which is the whole point of `resolveFrom`. The installed tree is linked
 * in rather than duplicated.
 */
export function copyFixtures(label) {
  const temporary = mkdtempSync(join(tmpdir(), `contract-codegen-${label}-`));
  cpSync(FIXTURES, temporary, { recursive: true });
  const zodManifest = createRequire(join(FIXTURES, "contracts", "noop.js")).resolve("zod/package.json");
  const modules = dirname(dirname(zodManifest));
  symlinkSync(modules, join(temporary, "node_modules"), "dir");
  return temporary;
}

export const DIVERGENCE_CLASSES = new Set([
  "strict-unknown-keys",
  "optional-accepts-null",
  "nullable-accepts-absent",
  "undefined-normalized-to-null",
  "refinement-not-carried",
  "degraded-to-unknown",
  "optional-null-widened-to-unknown",
]);

/**
 * npm links a registry devDependency's executable into the workspace root's
 * `node_modules/.bin` rather than the package's own, so the search climbs
 * instead of naming one directory: the toolchain is the same either way, and
 * which link exists is an install-layout detail no test should depend on.
 */
export function velarExecutable() {
  const name = process.platform === "win32" ? "velar.cmd" : "velar";
  for (let directory = PACKAGE_ROOT; ; directory = dirname(directory)) {
    const candidate = join(directory, "node_modules", ".bin", name);
    if (existsSync(candidate)) return candidate;
    if (dirname(directory) === directory) {
      throw new Error(`Cannot find the '${name}' executable; install @velarscript/cli`);
    }
  }
}

/** A Vel string literal that survives any payload, ASCII-only for safety. */
function velString(text) {
  let out = '"';
  for (const character of text) {
    const code = character.codePointAt(0);
    if (character === '"') out += '\\"';
    else if (character === "\\") out += "\\\\";
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16)}}`;
    else out += character;
  }
  return `${out}"`;
}

const DEFAULT_MODULE = "default";

export function renderDriver(imports, samples) {
  const byModule = new Map();
  for (const sample of samples) {
    const key = sample.module ?? DEFAULT_MODULE;
    if (!byModule.has(key)) byModule.set(key, new Set());
    byModule.get(key).add(sample.schema);
  }
  const lines = [
    "// Generated by the equivalence harness; not committed.",
    'import {expect} from "velar/test"',
    "",
  ];
  for (const key of [...byModule.keys()].sort()) {
    const specifier = imports[key];
    if (specifier === undefined) throw new Error(`no import declared for sample module '${key}'`);
    lines.push(`import {${[...byModule.get(key)].sort().join(", ")}} from ${JSON.stringify(specifier)}`);
  }
  lines.push(
    "",
    "def accepts<T>(target: Type<T>, value: unknown) -> bool:",
    "    try:",
    "        const parsed = target.parse(value)",
    "        return true",
    "    catch error:",
    "        return false",
    "",
  );
  samples.forEach((sample, index) => {
    const payload = velString(JSON.stringify(sample.payload));
    const matcher = sample.vel ? "toBeTruthy" : "toBeFalsy";
    lines.push(`test "sample ${index}: ${sample.schema} ${sample.vel ? "accepts" : "refuses"} ${sample.why}":`);
    lines.push(`    expect(accepts(${sample.schema}, Json.parse(${payload}))).${matcher}()`);
    lines.push("");
  });
  return `${lines.join("\n").trimEnd()}\n`;
}

/**
 * Copies the fixture project, writes the driver beside it, and runs
 * `velar test`. Nothing is written inside the repository.
 */
export function runVelSweep({ projectDirectory, imports, samples }) {
  const temporary = mkdtempSync(join(tmpdir(), "contract-codegen-equivalence-"));
  try {
    cpSync(projectDirectory, temporary, { recursive: true });
    const driver = join(temporary, "tests", "equivalence.test.vel");
    writeFileSync(driver, renderDriver(imports, samples), "utf8");
    const result = spawnSync(velarExecutable(), ["test", temporary], { encoding: "utf8" });
    return {
      status: result.status,
      output: `${result.stdout ?? ""}${result.stderr ?? ""}`,
      driver: readFileSync(driver, "utf8"),
    };
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

export function readSamples(path) {
  const parsed = JSON.parse(readFileSync(path, "utf8"));
  if (!Array.isArray(parsed.samples)) throw new Error(`${path} has no sample list`);
  return parsed.samples;
}
