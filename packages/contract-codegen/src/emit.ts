/**
 * Emission is deterministic: declarations are sorted by name, fields keep their
 * declared wire order, and the header records what produced the file.
 */

import { renderType, type Declaration } from "./ir.js";

export interface HeaderFields {
  readonly toolName: string;
  readonly toolVersion: string;
  readonly sourcePackage: string;
  readonly sourceVersion: string | null;
  readonly specifier: string;
  readonly schemaDigest: string;
  readonly manifestPath: string;
}

const INDENT = "    ";

export function renderHeader(header: HeaderFields): string {
  const version = header.sourceVersion === null ? "" : `@${header.sourceVersion}`;
  const source = header.sourcePackage === header.specifier
    ? `${header.sourcePackage}${version}`
    : `${header.sourcePackage}${version} "${header.specifier}"`;
  return [
    `// Generated by ${header.toolName} ${header.toolVersion}. Do not edit.`,
    `// Source: ${source}`,
    `// Schema digest: ${header.schemaDigest}`,
    `// Regenerate: velar-contract-codegen generate ${header.manifestPath}`,
  ].join("\n");
}

function renderDeclaration(declaration: Declaration): string {
  const doc = declaration.doc.map((line) => `// ${line}`);
  switch (declaration.kind) {
    case "enum": {
      const members = declaration.members.map((member) =>
        member.wire === null ? `${INDENT}${member.name}` : `${INDENT}${member.name} = ${JSON.stringify(member.wire)}`,
      );
      return [...doc, `export enum ${declaration.name}:`, ...members].join("\n");
    }
    case "record": {
      const fields = declaration.fields.map((field) => `${INDENT}${field.name}: ${renderType(field.type)}`);
      return [...doc, `export type ${declaration.name}:`, ...fields].join("\n");
    }
    case "alias":
      return [...doc, `export type ${declaration.name} = ${renderType(declaration.type)}`].join("\n");
  }
}

export function renderModule(header: HeaderFields, declarations: readonly Declaration[]): string {
  const blocks = declarations.map(renderDeclaration);
  return `${[renderHeader(header), ...blocks].join("\n\n")}\n`;
}

export interface ChannelConstant {
  readonly member: string;
  readonly wire: string;
}

export interface ChannelTypeBinding {
  /** Exported constant name in the emitted table. */
  readonly constant: string;
  /** Declaration name in the types module. */
  readonly type: string;
  readonly channel: string;
  readonly role: "request" | "response" | "event";
}

export function renderChannelTable(
  header: HeaderFields,
  enumName: string,
  typesImport: string,
  constants: readonly ChannelConstant[],
  bindings: readonly ChannelTypeBinding[],
): string {
  // A member-less enum is not a VelarScript declaration. Emitting one would put
  // the failure in the consuming project's `velar check` instead of here.
  if (constants.length === 0) {
    throw new Error(`channel table '${enumName}' has no channels; a VelarScript enum needs at least one member`);
  }
  const imported = [...new Set(bindings.map((binding) => binding.type))].sort();
  const blocks: string[] = [renderHeader(header)];
  if (imported.length > 0) blocks.push(`import {${imported.join(", ")}} from "${typesImport}"`);
  blocks.push(
    [
      "// Channel names. The wire string is the enum member's runtime value.",
      `export enum ${enumName}:`,
      ...constants.map((constant) =>
        constant.member === constant.wire
          ? `${INDENT}${constant.member}`
          : `${INDENT}${constant.member} = ${JSON.stringify(constant.wire)}`,
      ),
    ].join("\n"),
  );
  for (const binding of bindings) {
    blocks.push(
      [
        `// ${binding.channel} ${binding.role}`,
        `export const ${binding.constant}: Type<${binding.type}> = ${binding.type}`,
      ].join("\n"),
    );
  }
  return `${blocks.join("\n\n")}\n`;
}
