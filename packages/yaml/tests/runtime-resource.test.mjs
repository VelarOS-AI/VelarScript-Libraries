import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import test from "node:test";

import { parseYaml } from "../dist/index.js";

const artifactPath = fileURLToPath(new URL("../dist/index.js", import.meta.url));
const generatedPath = fileURLToPath(new URL("../src/generated/runtime.vel", import.meta.url));

test("the frozen artifact uses the package-owned YAML runtime", async () => {
  const artifact = await readFile(artifactPath, "utf8");
  assert.doesNotMatch(artifact, /from["']yaml["']/u);
  assert.doesNotMatch(artifact, /\brequire\s*\(/u);
  assert.doesNotMatch(artifact, /\bcreateRequire\b/u);
  assert.doesNotMatch(artifact, /\bfrom\s*["'](?:node:)?process["']/u);
  assert.match(artifact, /Map keys must be unique/u);
});

test("the generated YAML runtime is embedded and executable", async () => {
  const generated = await readFile(generatedPath, "utf8");
  assert.match(generated, /^\/\/\/ Generated by the YAML ESM runtime pipeline\. Do not edit\.\n/u);
  assert.doesNotMatch(generated, /\brequire\s*\(/u);
  assert.doesNotMatch(generated, /\bcreateRequire\b/u);
  assert.deepEqual(
    parseYaml("name: api\nports: [3000, 3001]\n"),
    { name: "api", ports: [3000, 3001] },
  );
  assert.throws(
    () => parseYaml("name: first\nname: second\n"),
    /Map keys must be unique/u,
  );
});
