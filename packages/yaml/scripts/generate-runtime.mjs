#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const packageRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const runtimeEntry = resolve(packageRoot, "scripts/yaml-runtime-entry.mjs");
const output = resolve(packageRoot, "src/generated/runtime.vel");
const notice = await readFile(resolve(packageRoot, "THIRD_PARTY_NOTICES.md"), "utf8");
const arguments_ = process.argv.slice(2);
const check = arguments_.length === 1 && arguments_[0] === "--check";

if (arguments_.length > (check ? 1 : 0)) {
  throw new Error("Usage: node scripts/generate-runtime.mjs [--check]");
}

const banner = `/*!\n${notice.trimEnd().split("\n").map((line) => ` * ${line}`.trimEnd()).join("\n")}\n */`;
const result = await build({
  absWorkingDir: packageRoot,
  entryPoints: [runtimeEntry],
  bundle: true,
  platform: "browser",
  format: "esm",
  target: "es2022",
  supported: { "template-literal": false },
  minify: true,
  treeShaking: true,
  legalComments: "none",
  banner: { js: banner },
  metafile: true,
  write: false,
  logLevel: "silent",
});

if (result.outputFiles.length !== 1) throw new Error("YAML runtime generation produced an unexpected output set");
const externalImports = Object.values(result.metafile.outputs)
  .flatMap((entry) => entry.imports)
  .filter((entry) => entry.external)
  .map((entry) => entry.path);
if (externalImports.length > 0) {
  throw new Error(`YAML runtime retained external imports: ${[...new Set(externalImports)].sort().join(", ")}`);
}

const javascript = result.outputFiles[0].text.trimEnd();
const generated = [
  "/// Generated by the YAML ESM runtime pipeline. Do not edit.",
  "type NativeYamlOptions:",
  "    strict: bool",
  "    uniqueKeys: bool",
  "    maxAliasCount: number",
  "",
  "extern js`",
  ...javascript.split("\n").map((line) => `    ${line}`),
  "`:",
  "    export def parse(source: string, options: NativeYamlOptions) -> unknown",
  "",
  "export def parseNativeYaml(source: string, maxAliases: number) -> unknown:",
  "    return parse(source, {strict: true, uniqueKeys: true, maxAliasCount: maxAliases})",
  "",
].join("\n");
const existing = await readFile(output, "utf8").catch((error) => {
  if (error?.code === "ENOENT") return null;
  throw error;
});

if (existing === generated) {
  process.stdout.write("YAML embedded ESM runtime is current.\n");
} else if (check) {
  throw new Error("YAML ESM runtime is stale; run npm run generate:runtime --workspace @velarscript-labs/yaml");
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, generated, "utf8");
  process.stdout.write(`Generated YAML embedded ESM runtime (${String(result.outputFiles[0].contents.byteLength)} JavaScript bytes).\n`);
}
